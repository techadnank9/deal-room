import EmailReplyParser from "email-reply-parser";
import { normalizeMessageId } from "./compose";
import type { Inbound } from "./types";

/** Strip quoted history ("On ... wrote:", "> ..."), and common signatures from a reply. */
export function cleanReply(text: string): string {
  if (!text) return "";
  try {
    const out = new EmailReplyParser().parseReply(text.replace(/\r\n/g, "\n"));
    return out.trim() || text.trim();
  } catch {
    return text.trim();
  }
}

function h(inbound: Inbound, name: string): string {
  return (inbound.headers[name] ?? "").toLowerCase();
}

export function isAutoReply(inbound: Inbound): boolean {
  const autoSubmitted = h(inbound, "auto-submitted").trim();
  if (autoSubmitted && autoSubmitted !== "no") return true;
  for (const k of ["x-autoreply", "x-autorespond", "x-auto-response-suppress", "x-autogenerated"]) {
    if (k in inbound.headers) return true;
  }
  if (/^(bulk|auto_reply|junk)$/.test(h(inbound, "precedence").trim())) return true;
  return /^\s*(automatic reply|out of office|auto:)/i.test(inbound.subject ?? "");
}

export function isBounce(inbound: Inbound): boolean {
  const from = (inbound.from ?? "").toLowerCase();
  if (/^(mailer-daemon|postmaster)@/.test(from) || from === "mailer-daemon" || from === "postmaster") return true;
  if (/(undeliverable|delivery status notification|mail delivery failed)/i.test(inbound.subject ?? "")) return true;
  const ct = h(inbound, "content-type");
  return ct.includes("multipart/report") && (ct.includes("delivery-status") || !ct.includes("report-type"));
}

/** Returns the sent Message-ID this inbound message replies to, via In-Reply-To then References (newest first). */
export function matchThread(inbound: Inbound, sentMessageIds: Set<string>): string | null {
  const candidates = [
    ...(inbound.inReplyTo ? inbound.inReplyTo.split(/\s+/) : []),
    ...[...inbound.references].reverse(),
  ].filter(Boolean);
  for (const raw of candidates) {
    const id = normalizeMessageId(raw);
    const bare = id.slice(1, -1);
    if (sentMessageIds.has(id)) return id;
    if (sentMessageIds.has(bare)) return bare;
    if (sentMessageIds.has(raw)) return raw;
  }
  return null;
}
